
-- Food Donation Management System
-- Database: Supabase PostgreSQL

CREATE TABLE IF NOT EXISTS donors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS food_donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id BIGINT NOT NULL
        REFERENCES donors(id) ON DELETE RESTRICT,
    food_name VARCHAR(150) NOT NULL,
    quantity NUMERIC(10, 2) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(30) NOT NULL DEFAULT 'servings',
    expiry_date DATE NOT NULL,
    pickup_address TEXT NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (status IN (
            'available',
            'reserved',
            'collected',
            'expired',
            'cancelled'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS donation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id BIGINT NOT NULL
        REFERENCES food_donations(id) ON DELETE RESTRICT,
    requester_name VARCHAR(100) NOT NULL,
    requester_email VARCHAR(255) NOT NULL,
    requester_phone VARCHAR(20) NOT NULL,
    requested_quantity NUMERIC(10, 2) NOT NULL
        CHECK (requested_quantity > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'approved',
            'rejected',
            'completed',
            'cancelled'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indexes for common searches
CREATE INDEX IF NOT EXISTS idx_donations_status
    ON food_donations(status);

CREATE INDEX IF NOT EXISTS idx_donations_expiry
    ON food_donations(expiry_date);

CREATE INDEX IF NOT EXISTS idx_donations_donor
    ON food_donations(donor_id);

CREATE INDEX IF NOT EXISTS idx_requests_donation
    ON donation_requests(donation_id);

CREATE INDEX IF NOT EXISTS idx_requests_status
    ON donation_requests(status);

-- Automatically update updated_at whenever a record changes
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS update_food_donations_updated_at
    ON food_donations;

CREATE TRIGGER update_food_donations_updated_at
BEFORE UPDATE ON food_donations
FOR EACH ROW
EXECUTE FUNCTION update_updated_at();

DROP TRIGGER IF EXISTS update_donation_requests_updated_at
    ON donation_requests;

CREATE TRIGGER update_donation_requests_updated_at
BEFORE UPDATE ON donation_requests
FOR EACH ROW
EXECUTE FUNCTION update_updated_at();

-- Enable Row Level Security.
-- Server-side access must be implemented securely.
ALTER TABLE donors ENABLE ROW LEVEL SECURITY;
ALTER TABLE food_donations ENABLE ROW LEVEL SECURITY;
ALTER TABLE donation_requests ENABLE ROW LEVEL SECURITY;
